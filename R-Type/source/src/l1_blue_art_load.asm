 ORG $C200
load_blue_art:
 LD A,$6F
 OUT ($F4),A
 LD IX,$C260
 LD A,BLUE_CHUNKS
 LD DE,$C900
loop:
 PUSH AF
 LD L,(IX)
 LD H,0
 ADD HL,HL
 ADD HL,HL
 ADD HL,HL
 LD BC,$2000
 ADD HL,BC
 LD C,(IX+1)
 LD B,0
 LDIR
 INC IX
 INC IX
 POP AF
 DEC A
 JR NZ,loop
 IF BLUE_TAIL > 0
 LD HL,$C25D
 LD BC,BLUE_TAIL
 LDIR
 ENDIF
 LD HL,$C900
 LD DE,$C300
 CALL $DE4F
 RET
 ASSERT $ <= $C25D
