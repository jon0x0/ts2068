"""Experimental level-one TS2068 copy-and-run cartridge, separate from art proof."""
from pathlib import Path
import hashlib,json,subprocess,sys

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'build/native'; ASM=ROOT/'src/native_boot.asm'
def sha(b):return hashlib.sha256(b).hexdigest()
def main():
    OUT.mkdir(parents=True,exist_ok=True)
    from fullgame_context import FULL,raw_snapshot
    ram=raw_snapshot()
    meta=json.loads((ROOT/'build/spectrum_baseline/postload_checkpoint.json').read_text())
    assert len(ram)==49152 and (FULL or sha(ram)==meta['memory_sha256'])
    changes=[]
    if '--native-input' in sys.argv:
        from native_compat import patch_input
        ram,changes=patch_input(ROOT,ram)
    c=meta['cpu']; assert c['pc']==0x8634 and c['im']==2
    # Every 8K HOME destination has a different physical source chunk.
    mapping=[(7,2),(1,3),(2,4),(3,5),(5,6),(6,7)]
    rom=bytearray(b'\xff'*65536)
    for source,dest in mapping:rom[source*8192:(source+1)*8192]=ram[(dest-2)*8192:(dest-1)*8192]
    (OUT/'snapshot.bin').write_bytes(ram)
    lines=['; Generated by scripts/build_native.py. Original graphics; first level only.',
      '; Chunks: 0=native input,7->HOME2,1->HOME3,2->HOME4,3->HOME5,4=bootstrap,5->HOME6,6->HOME7.',
      '; DI throughout transfer. No stack operations while a source overlay is selected.',
      'ORG $8000','DB 2,2','DW entry','DB $EF,1','DW 0','entry: DI','LD A,0','OUT ($FF),A']
    for source,dest in mapping:
        if source==2:continue
        lines += [f'LD A,${0x10|(1<<source):02X}','OUT ($F4),A',f'LD HL,${source*8192:04X}',
                  f'LD DE,${dest*8192:04X}','LD BC,$2000','LDIR','LD A,$10','OUT ($F4),A']
    lines += ['LD HL,helper_image','LD DE,$A000','LD BC,helper_end-helper','LDIR','JP $A000',
              'helper_image:','DISP $A000','helper: LD A,$04','OUT ($F4),A','LD HL,$4000',
              'LD DE,$8000','LD BC,$2000','LDIR','LD A,$10','OUT ($F4),A','JP cleanup',
              'helper_end:','ENT','cleanup: LD A,$18','OUT ($F4),A','LD HL,$6000',
              'LD DE,$A000','LD BC,$2000','LDIR','LD A,$10','OUT ($F4),A']
    # Temporary helper is completely overwritten from original chunk5 payload.
    # Restore AF pairs using a temporary screen stack, then repair its four bytes.
    for addr,key in ((0x58fd,"af'"),(0x58ff,'af')):
        lines += [f'LD HL,${c[key]:04X}',f'LD (${addr:04X}),HL']
    lines += ['LD SP,$58FD','POP AF','EX AF,AF\'','POP AF']
    for addr in (0x58fd,0x58ff):
        word=int.from_bytes(ram[addr-0x4000:addr-0x4000+2],'little')
        lines += [f'LD HL,${word:04X}',f'LD (${addr:04X}),HL']
    for reg in ('bc','de','hl'):lines += [f'LD {reg.upper()},${c[reg+chr(39)]:04X}']
    lines += ['EXX']
    for reg in ('bc','de','hl','ix','iy','sp'):lines += [f'LD {reg.upper()},${c[reg]:04X}']
    lines += [f'LD A,${c["i"]:02X}','LD I,A','IM 2','JP handoff',
      'ASSERT $ < $862F','DS $862F-$,$FF',
      '; A is dead at $8634: first routine loads A from $C4B1 before reading it.',
      '; Restore all other general registers/flags. R and frame phase are not restored.',
      f'handoff: LD A,{1 if changes else 0}','EI','OUT ($F4),A','ASSERT $ == $8634']
    ASM.write_text('\n'.join(line if ':' in line and not line.startswith(';') else '        '+line for line in lines)+'\n')
    assembler=ROOT.parent/'sinistar/tools/sjasmplus/sjasmplus-1.20.3.win/sjasmplus.exe'
    result=subprocess.run([str(assembler),f'--raw={OUT/"boot.bin"}',str(ASM)],cwd=ROOT,capture_output=True,text=True)
    (OUT/'assembly.log').write_text(result.stdout+result.stderr)
    if result.returncode:raise SystemExit(result.stdout+result.stderr)
    boot=(OUT/'boot.bin').read_bytes(); assert len(boot)==0x634
    rom[0x8000:0x8000+len(boot)]=boot
    if changes:
        code=(OUT/'input.bin').read_bytes()
        rom[0x1a00:0x1a00+len(code)]=code
    raw=bytes(rom);dck=bytes([0]+[2]*8)+raw
    (OUT/'RType_level1_native_experimental.bin').write_bytes(raw)
    (OUT/'RType_level1_native_experimental.dck').write_bytes(dck)
    for ext,data in (('bin',raw),('dck',dck)):
        (OUT/('RType_level1_native_experimental_r2.'+ext)).write_bytes(data)
    (OUT/'manifest.json').write_text(json.dumps(dict(revision='r2-key-release',bin_sha256=sha(raw),dck_sha256=sha(dck),
      checkpoint=meta,mapping=mapping,handoff=0x8634,patches=changes,
      limitation='Experimental original-graphics level1 baseline. Native keyboard/joystick merge optional; audio/ECM and subsequent level loading not yet ported.'),indent=2))
    print('Built experimental native level1',sha(raw))
if __name__=='__main__':main()





